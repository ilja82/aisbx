//! The model fetcher: one small sandbox per LiteLLM connection, `aisbx-models-<name>`, that asks
//! the gateway for its model list. No agent runs in it and it mounts nothing; its only egress is
//! the gateway's host, where the sbx proxy swaps the connection's placeholder for the key. The
//! dashboard runs it after a key is stored, at start and in the create wizard when the last fetch
//! is a day old, and when asked; the list it reads ends up in the connection's harvest file
//! ([`crate::litellm::harvest_file`]).

use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};

use crate::job::Step;
use crate::litellm::{self, Connection};

/// The fetcher's agent and kit folder name, which `sbx ls` reports as its agent.
pub const AGENT: &str = "aisbx-models";

/// The model-list script, run in the fetcher with `--force`: it asks `/v1/models` and
/// `/model/info` and writes [`crate::sbx::MODELS_CACHE`].
pub const SCRIPT: &str = include_str!("../assets/litellm-models.sh");

/// How long a fetch stays fresh: the dashboard and the create wizard ask again only after this.
pub const FRESH_SECS: u64 = 24 * 60 * 60;

/// The fetcher sandbox of a connection.
pub fn sandbox_name(conn: &str) -> String {
    format!("{AGENT}-{conn}")
}

/// Is this a fetcher sandbox, by the agent `sbx ls` reports? The dashboard lists none of them.
pub fn is_fetcher(agent: &str) -> bool {
    agent == AGENT
}

/// The connection a fetcher sandbox reads for.
pub fn connection_of(sandbox: &str) -> Option<&str> {
    sandbox
        .strip_prefix(AGENT)?
        .strip_prefix('-')
        .filter(|n| litellm::valid_name(n))
}

/// Where a connection's fetcher kit lives: `<litellm dir>/<name>/aisbx-models/`.
pub fn kit_dir_in(root: &Path, conn: &str) -> PathBuf {
    root.join(conn).join(AGENT)
}

/// Write the fetcher's kit for a connection and return its directory. Rewritten every time, so the
/// allowed host is always the connection's.
pub fn ensure_kit_in(root: &Path, c: &Connection) -> Result<PathBuf> {
    litellm::validate(c)?;
    let kit = kit_dir_in(root, &c.name);
    fs::create_dir_all(&kit).with_context(|| format!("creating {}", kit.display()))?;
    fs::write(crate::kits::descriptor_path(&kit), descriptor(c))
        .with_context(|| format!("writing the model fetcher of connection “{}”", c.name))?;
    Ok(kit)
}

/// A v3 workload on Docker's shell template (it has `curl` and `jq`), allowed the gateway's host
/// and nothing else. Every value in it was checked by [`litellm::validate`].
fn descriptor(c: &Connection) -> String {
    let name = c.name.as_str();
    let host = litellm::host(&c.url);
    format!(
        "# syntax=docker/sandbox-kit:3\n\
         # Generated by aisbx — do not edit; rewritten before every fetch.\n\
         #\n\
         # Reads the model list of the LiteLLM connection \"{name}\" for aisbx. No agent runs here.\n\
         schemaVersion: \"3\"\n\
         kind: workload\n\
         displayName: \"aisbx model list: {name}\"\n\
         description: \"Reads the model list of the LiteLLM connection {name} for aisbx.\"\n\
         \n\
         build: |\n\
         \x20 FROM docker/sandbox-templates:shell-docker\n\
         \x20 ENV SBX_KIT_AISBX_MODELS=\"1\"\n\
         \x20 LABEL com.docker.sandboxes.flavor=\"{AGENT}\"\n\
         \n\
         capabilities:\n\
         \x20 - type: com.docker.sandbox/sbx@1\n\
         \x20 - type: com.docker.sandbox/network-policy@1\n\
         \x20   config:\n\
         \x20     runtime:\n\
         \x20       allow:\n\
         \x20         - \"{host}:443\"\n"
    )
}

/// `sbx create` of a connection's fetcher: mountless, one CPU, 1 GiB.
pub fn create_argv(conn: &str, kit: &Path) -> Vec<String> {
    let name = sandbox_name(conn);
    crate::sbx::create_argv(crate::sbx::Create {
        name: &name,
        agent: AGENT,
        agent_kit: Some(kit),
        kit_dirs: &[kit],
        workspace: Path::new(""),
        mounts: &[],
        clone: false,
        ports: &[],
        skills: None,
        deny_network: &[],
        static_mcp: &[],
        cpus: Some(1),
        memory: Some("1g"),
        template: None,
    })
}

/// Run the model-list script in the fetcher, its text on stdin: `sbx exec -i <fetcher> sh -s --
/// --base-url <url> --bearer <placeholder> --force`.
pub fn fetch_argv(c: &Connection) -> Vec<String> {
    let mut argv: Vec<String> = ["sbx", "exec", "-i"].map(String::from).to_vec();
    argv.push(sandbox_name(&c.name));
    argv.extend(["sh", "-s", "--", "--base-url"].map(String::from));
    argv.push(c.url.trim_end_matches('/').to_string());
    argv.push("--bearer".into());
    argv.push(litellm::placeholder(&c.name));
    argv.push("--force".into());
    argv
}

/// The steps of one fetch: the fetcher's create where it does not exist yet, then the script.
/// The list is read back afterwards ([`crate::app::App::harvest_models`]).
pub fn steps(c: &Connection, kit: &Path, exists: bool) -> Vec<Step> {
    let mut steps = Vec::new();
    if !exists {
        steps.push(
            Step::new(
                format!("sbx create {}", sandbox_name(&c.name)),
                create_argv(&c.name, kit),
            )
            .noting("a small sandbox that only reads the model list — built once"),
        );
    }
    let mut fetch = Step::new(format!("fetch the model list of {}", c.name), fetch_argv(c));
    fetch.stdin = Some(SCRIPT.to_string());
    steps.push(fetch);
    steps
}

/// The file that says when a connection's list was last asked for.
fn stamp_in(root: &Path, conn: &str) -> PathBuf {
    root.join(conn).join("fetch-attempted")
}

/// Is a connection's list due for a fetch: not asked for in the last [`FRESH_SECS`], succeeded or
/// not?
pub fn due_in(root: &Path, conn: &str, now: u64) -> bool {
    let last = fs::read_to_string(stamp_in(root, conn))
        .ok()
        .and_then(|t| t.trim().parse::<u64>().ok());
    match last {
        Some(at) if at <= now => now - at >= FRESH_SECS,
        _ => true,
    }
}

/// Should the create wizard fetch a connection's list before its Harness step? Only when the
/// cached list is missing or a day old (`fetched_at`, its last success), and the list was not
/// asked for in the last day either ([`due_in`]), so a failed fetch is not retried every time.
pub fn stale_in(root: &Path, conn: &str, fetched_at: Option<i64>, now: u64) -> bool {
    let fresh = fetched_at.is_some_and(|at| (now as i64).saturating_sub(at) < FRESH_SECS as i64);
    !fresh && due_in(root, conn, now)
}

/// Record that a connection's list was asked for now.
pub fn mark_in(root: &Path, conn: &str, now: u64) -> Result<()> {
    let path = stamp_in(root, conn);
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
    }
    fs::write(&path, format!("{now}\n")).with_context(|| format!("writing {}", path.display()))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn conn() -> Connection {
        Connection {
            name: "acme".into(),
            url: "https://litellm.example.com/".into(),
        }
    }

    fn scratch(tag: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!(
            "aisbx-fetch-{tag}-{}-{}",
            std::process::id(),
            crate::state::now_epoch()
        ));
        let _ = fs::remove_dir_all(&dir);
        dir
    }

    #[test]
    fn a_fetcher_is_named_after_its_connection() {
        assert_eq!(sandbox_name("acme"), "aisbx-models-acme");
        assert_eq!(connection_of("aisbx-models-acme"), Some("acme"));
        assert_eq!(connection_of("aisbx-models-"), None);
        assert_eq!(connection_of("claude-litellm-acme"), None);
        assert!(is_fetcher("aisbx-models"));
        assert!(!is_fetcher("claude"));
    }

    #[test]
    fn the_fetcher_kit_is_a_workload_that_reaches_only_the_gateway() {
        let root = scratch("kit");
        let dir = ensure_kit_in(&root, &conn()).unwrap();
        assert!(dir.ends_with("acme/aisbx-models"));
        let text = fs::read_to_string(crate::kits::descriptor_path(&dir)).unwrap();
        let doc = crate::kits::load_descriptor(&text).unwrap();
        assert_eq!(doc["kind"].as_str(), Some("workload"));
        assert!(doc["build"]
            .as_str()
            .unwrap()
            .starts_with("FROM docker/sandbox-templates:shell-docker\n"));
        let caps = crate::kits::capabilities(&doc);
        let net = caps
            .iter()
            .find(|c| c.kind == "network-policy@1")
            .expect("a network policy");
        let allow: Vec<&str> = net.config["runtime"]["allow"]
            .as_vec()
            .unwrap()
            .iter()
            .filter_map(|v| v.as_str())
            .collect();
        assert_eq!(allow, ["litellm.example.com:443"]);
        assert!(net.config["install"].is_badvalue());
        assert!(
            !caps.iter().any(|c| c.kind == "lifecycle@1"),
            "no hook runs"
        );
        let _ = fs::remove_dir_all(&root);
    }

    #[test]
    fn a_fetch_creates_the_fetcher_once_and_runs_the_script_from_stdin() {
        let kit = Path::new("/state/litellm/acme/aisbx-models");
        let first = steps(&conn(), kit, false);
        assert_eq!(first.len(), 2);
        let create = &first[0].argv;
        assert_eq!(&create[..2], ["sbx", "create"]);
        assert!(create
            .windows(2)
            .any(|w| w == ["--name", "aisbx-models-acme"]));
        assert!(create.windows(2).any(|w| w == ["--cpus", "1"]));
        assert_eq!(
            create.last().map(String::as_str),
            Some(kit.to_str().unwrap())
        );
        assert!(
            !create.iter().any(|a| a == "--kit"),
            "the workload is the positional"
        );
        let again = steps(&conn(), kit, true);
        assert_eq!(again.len(), 1);
        let fetch = &again[0];
        assert_eq!(
            fetch.argv,
            [
                "sbx",
                "exec",
                "-i",
                "aisbx-models-acme",
                "sh",
                "-s",
                "--",
                "--base-url",
                "https://litellm.example.com",
                "--bearer",
                "sbx-cs-aisbx-llm-acme",
                "--force"
            ]
        );
        assert_eq!(fetch.stdin.as_deref(), Some(SCRIPT));
        assert!(SCRIPT.starts_with("#!/bin/sh\n"));
    }

    /// Builds a fetcher for a probe connection on `example.com`, which serves no `/v1/models`:
    /// the create and the exec must work, the fetch must fail with the script's exit 1, and the
    /// fetcher must reach no other host. Removes the fetcher afterwards.
    #[test]
    #[ignore = "creates and removes a sandbox on this host"]
    fn live_the_fetcher_builds_and_runs_the_script_from_stdin() {
        let root = scratch("live");
        let probe = Connection {
            name: "probe-live".into(),
            url: "https://example.com".into(),
        };
        let kit = ensure_kit_in(&root, &probe).unwrap();
        let name = sandbox_name(&probe.name);
        let _ = crate::job::run_quiet(&Step::new("rm", crate::sbx::rm_argv(&name)));
        let steps = steps(&probe, &kit, false);
        let created = crate::job::run_quiet(&steps[0]);
        let fetched = created && crate::job::run_quiet(&steps[1]);
        let out = std::process::Command::new("sbx")
            .args([
                "exec",
                &name,
                "sh",
                "-c",
                "curl -s -o /dev/null -w %{http_code} https://example.org",
            ])
            .stdin(std::process::Stdio::null())
            .output();
        let _ = crate::job::run_quiet(&Step::new("rm", crate::sbx::rm_argv(&name)));
        let _ = fs::remove_dir_all(&root);
        assert!(created, "sbx create of the fetcher");
        assert!(!fetched, "example.com serves no model list");
        let other = out.map(|o| String::from_utf8_lossy(&o.stdout).to_string());
        println!("another host from the fetcher: {other:?}");
        assert!(!matches!(other.as_deref(), Ok("200")), "{other:?}");
    }

    #[test]
    fn a_list_is_due_once_a_day() {
        let root = scratch("due");
        assert!(due_in(&root, "acme", 1_000_000), "never asked");
        mark_in(&root, "acme", 1_000_000).unwrap();
        assert!(
            !due_in(&root, "acme", 1_000_000 + 23 * 60 * 60),
            "23 hours on"
        );
        assert!(
            due_in(&root, "acme", 1_000_000 + 25 * 60 * 60),
            "25 hours on"
        );
        assert!(!due_in(&root, "acme", 1_000_000 + FRESH_SECS - 1));
        assert!(due_in(&root, "acme", 1_000_000 + FRESH_SECS));
        assert!(due_in(&root, "acme", 999_000), "a stamp from the future");
        let _ = fs::remove_dir_all(&root);
    }

    #[test]
    fn the_wizard_reuses_a_list_younger_than_a_day() {
        let root = scratch("stale");
        let now = 10_000_000;
        let day = FRESH_SECS as i64;
        assert!(stale_in(&root, "acme", None, now), "no list, never asked");
        assert!(!stale_in(&root, "acme", Some(now as i64 - day + 1), now));
        assert!(stale_in(&root, "acme", Some(now as i64 - day), now));
        mark_in(&root, "acme", now - 60).unwrap();
        assert!(!stale_in(&root, "acme", None, now), "asked a minute ago");
        assert!(!stale_in(&root, "acme", Some(now as i64 - day), now));
        assert!(stale_in(&root, "acme", None, now + FRESH_SECS));
        let _ = fs::remove_dir_all(&root);
    }
}
