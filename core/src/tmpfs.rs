//! RAM-backed copies of the kits that declare volumes, for `aisbx up --tmpfs-volumes`. A copy is
//! its kit with `tmpfs: true` on every `volume@1`, in a folder of the kit's name.

use std::collections::BTreeSet;
use std::fs::{self, File};
use std::path::{Path, PathBuf};

use anyhow::{anyhow, bail, ensure, Context, Result};
use yaml_rust2::{Yaml, YamlEmitter};

use crate::kits;
use crate::state::state_dir;

/// The capability that declares a volume, as [`kits::capabilities`] names it.
const VOLUME: &str = "volume@1";

/// The first lines of a copy's descriptor. The copy keeps none of the kit's own comments.
const HEADER: &str = "# syntax=docker/sandbox-kit:3\n\
# Generated by aisbx from the kit of the same name, with every volume in RAM (tmpfs) - do not\n\
# edit: rewritten from the checkout's kits/ at every `aisbx up --tmpfs-volumes` and rebuild.\n";

/// Where the copies live. Under the test guard, a scratch folder instead.
pub fn kits_dir() -> PathBuf {
    if cfg!(any(test, feature = "test-support")) {
        std::env::temp_dir().join("aisbx-tests-tmpfs")
    } else {
        state_dir().join("tmpfs")
    }
}

/// A kit path (as `sbx inspect` reports one) that is one of the copies: the sandbox built from it
/// has its volumes in RAM.
pub fn is_copy(path: &Path) -> bool {
    path.starts_with(kits_dir())
}

/// How many volumes a parsed descriptor keeps on disk: each `volume@1` without `tmpfs: true`.
pub fn disk_volumes(doc: &Yaml) -> usize {
    kits::capabilities(doc)
        .iter()
        .filter(|c| c.kind == VOLUME && c.config["tmpfs"].as_bool() != Some(true))
        .count()
}

/// Whether the kit in `dir` keeps a volume on disk; false for a folder without a descriptor (a
/// kit path of a sandbox whose checkout has moved).
pub fn declares_disk_volumes(dir: &Path) -> Result<bool> {
    let path = kits::descriptor_path(dir);
    let text = match fs::read_to_string(&path) {
        Ok(text) => text,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(false),
        Err(e) => return Err(e).with_context(|| format!("reading {}", path.display())),
    };
    let doc =
        kits::load_descriptor(&text).with_context(|| format!("parsing {}", path.display()))?;
    Ok(disk_volumes(&doc) > 0)
}

/// The copy of the kit in `dir`, written now - or `dir` itself for a kit that keeps no volume on
/// disk, which needs none.
pub fn copy_of(dir: &Path) -> Result<PathBuf> {
    let kit = dir
        .file_name()
        .and_then(|n| n.to_str())
        .ok_or_else(|| anyhow!("{} names no kit", dir.display()))?;
    let path = kits::descriptor_path(dir);
    let text = fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
    let doc =
        kits::load_descriptor(&text).with_context(|| format!("parsing {}", path.display()))?;
    if disk_volumes(&doc) == 0 {
        return Ok(dir.to_path_buf());
    }
    let descriptor = descriptor_in_ram(&text, kit)?;
    let root = kits_dir();
    fs::create_dir_all(&root).with_context(|| format!("creating {}", root.display()))?;
    // Outside every copy: a file in a kit's folder is part of what sbx builds.
    let lock = File::options()
        .create(true)
        .truncate(false)
        .write(true)
        .open(root.join(".lock"))
        .with_context(|| format!("opening the lock in {}", root.display()))?;
    lock.lock()
        .with_context(|| format!("locking {}", root.display()))?;
    let copy = root.join(kit);
    sync(dir, &copy, &descriptor)
        .with_context(|| format!("copying {kit} to {}", copy.display()))?;
    Ok(copy)
}

/// [`copy_of`] for each kit, in the same order.
pub fn copies(dirs: &[PathBuf]) -> Result<Vec<PathBuf>> {
    dirs.iter().map(|d| copy_of(d)).collect()
}

/// The descriptor of a kit's copy: each `volume@1` (a capability group's members included) with
/// `tmpfs: true`, everything else as parsed. Refused when the re-emitted text does not read back as
/// exactly that document, and for a kit with no volume on disk.
pub fn descriptor_in_ram(text: &str, kit: &str) -> Result<String> {
    let mut doc = kits::load_descriptor(text).with_context(|| format!("parsing {kit}"))?;
    ensure!(
        doc["schemaVersion"].as_str() == Some("3"),
        "{kit} is no kit-spec v3 kit"
    );
    let capabilities = doc
        .as_mut_hash()
        .and_then(|h| h.get_mut(&Yaml::String("capabilities".into())))
        .and_then(Yaml::as_mut_vec)
        .ok_or_else(|| anyhow!("{kit} declares no capabilities"))?;
    let mut moved = 0;
    for item in capabilities.iter_mut() {
        moved += in_ram(item, kit)?;
    }
    ensure!(moved > 0, "{kit} keeps no volume on disk");
    let mut body = String::new();
    {
        let mut emitter = YamlEmitter::new(&mut body);
        emitter.multiline_strings(true);
        emitter
            .dump(&doc)
            .map_err(|e| anyhow!("writing {kit}'s descriptor: {e:?}"))?;
    }
    let body = body.strip_prefix("---\n").unwrap_or(&body);
    let out = format!("{HEADER}{body}\n");
    let back = kits::load_descriptor(&out).with_context(|| format!("re-reading {kit}'s copy"))?;
    ensure!(
        back == doc,
        "{kit}'s copy would not read back as the kit with its volumes in RAM"
    );
    Ok(out)
}

/// Puts the volume `item` declares - or, for a capability group, each member's - in RAM, and says
/// how many it changed.
fn in_ram(item: &mut Yaml, kit: &str) -> Result<usize> {
    let Some(entry) = item.as_mut_hash() else {
        return Ok(0);
    };
    if let Some(group) = entry.get_mut(&Yaml::String("group".into())) {
        let members = group
            .as_mut_hash()
            .and_then(|g| g.get_mut(&Yaml::String("capabilities".into())))
            .and_then(Yaml::as_mut_vec);
        let mut moved = 0;
        for member in members.into_iter().flatten() {
            moved += in_ram(member, kit)?;
        }
        return Ok(moved);
    }
    let kind = entry
        .get(&Yaml::String("type".into()))
        .and_then(Yaml::as_str)
        .unwrap_or_default();
    if kind.strip_prefix("com.docker.sandbox/").unwrap_or(kind) != VOLUME {
        return Ok(0);
    }
    let config = entry
        .get_mut(&Yaml::String("config".into()))
        .and_then(Yaml::as_mut_hash)
        .ok_or_else(|| anyhow!("{kit} declares a volume without a config mapping"))?;
    let tmpfs = Yaml::String("tmpfs".into());
    if config.get(&tmpfs).and_then(Yaml::as_bool) == Some(true) {
        return Ok(0);
    }
    config.insert(tmpfs, Yaml::Boolean(true));
    Ok(1)
}

/// Brings the folder `dst` to `src` with `descriptor` as its descriptor: a file written only when
/// its bytes or mode differ, and whatever `src` no longer has removed.
fn sync(src: &Path, dst: &Path, descriptor: &str) -> Result<()> {
    let descriptor_name = kits::descriptor_path(dst)
        .file_name()
        .map(PathBuf::from)
        .ok_or_else(|| anyhow!("{} names no kit", dst.display()))?;
    if dst.exists() && !dst.is_dir() {
        fs::remove_file(dst).with_context(|| format!("removing {}", dst.display()))?;
    }
    fs::create_dir_all(dst).with_context(|| format!("creating {}", dst.display()))?;
    let mut keep = BTreeSet::from([descriptor_name.clone()]);
    copy_tree(src, dst, Path::new(""), &descriptor_name, &mut keep)?;
    write_if_changed(&dst.join(&descriptor_name), descriptor.as_bytes(), None)?;
    prune(dst, Path::new(""), &keep)
}

fn copy_tree(
    src: &Path,
    dst: &Path,
    rel: &Path,
    descriptor_name: &Path,
    keep: &mut BTreeSet<PathBuf>,
) -> Result<()> {
    let from = src.join(rel);
    let entries = fs::read_dir(&from).with_context(|| format!("reading {}", from.display()))?;
    for entry in entries {
        let entry = entry.with_context(|| format!("reading {}", from.display()))?;
        let rel_path = rel.join(entry.file_name());
        if rel_path == descriptor_name {
            continue; // the copy's own descriptor takes its place
        }
        let meta = fs::symlink_metadata(entry.path())
            .with_context(|| format!("reading {}", entry.path().display()))?;
        let target = dst.join(&rel_path);
        if meta.is_dir() {
            if target.exists() && !target.is_dir() {
                fs::remove_file(&target)
                    .with_context(|| format!("removing {}", target.display()))?;
            }
            fs::create_dir_all(&target)
                .with_context(|| format!("creating {}", target.display()))?;
            keep.insert(rel_path.clone());
            copy_tree(src, dst, &rel_path, descriptor_name, keep)?;
        } else if meta.is_file() {
            let bytes = fs::read(entry.path())
                .with_context(|| format!("reading {}", entry.path().display()))?;
            write_if_changed(&target, &bytes, Some(&meta))?;
            keep.insert(rel_path);
        } else {
            // A link would copy what it points to today, or nothing: not the kit sbx builds.
            bail!(
                "{} is neither a file nor a folder, which a kit's copy cannot hold",
                entry.path().display()
            );
        }
    }
    Ok(())
}

/// Writes `bytes` to `path` (through a temporary file and a rename, so no reader sees half of it)
/// unless it holds them already with `like`'s permissions.
fn write_if_changed(path: &Path, bytes: &[u8], like: Option<&fs::Metadata>) -> Result<()> {
    if path.is_dir() {
        fs::remove_dir_all(path).with_context(|| format!("removing {}", path.display()))?;
    }
    let same_bytes = fs::read(path).is_ok_and(|old| old == bytes);
    let same_mode = match like {
        None => true,
        Some(src) => fs::metadata(path).is_ok_and(|now| same_permissions(&now, src)),
    };
    if same_bytes && same_mode {
        return Ok(());
    }
    let name = path
        .file_name()
        .ok_or_else(|| anyhow!("{} names no file", path.display()))?;
    let tmp = path.with_file_name(format!(".{}.aisbx-tmp", name.to_string_lossy()));
    fs::write(&tmp, bytes).with_context(|| format!("writing {}", tmp.display()))?;
    if let Some(src) = like {
        fs::set_permissions(&tmp, src.permissions())
            .with_context(|| format!("setting the mode of {}", tmp.display()))?;
    }
    fs::rename(&tmp, path).with_context(|| format!("replacing {}", path.display()))
}

#[cfg(unix)]
fn same_permissions(a: &fs::Metadata, b: &fs::Metadata) -> bool {
    use std::os::unix::fs::PermissionsExt;
    a.permissions().mode() & 0o7777 == b.permissions().mode() & 0o7777
}

#[cfg(not(unix))]
fn same_permissions(a: &fs::Metadata, b: &fs::Metadata) -> bool {
    a.permissions().readonly() == b.permissions().readonly()
}

/// Removes from the copy what its kit does not have (any more): files, folders, and a temporary
/// file a crash left.
fn prune(dst: &Path, rel: &Path, keep: &BTreeSet<PathBuf>) -> Result<()> {
    let at = dst.join(rel);
    let entries = fs::read_dir(&at).with_context(|| format!("reading {}", at.display()))?;
    for entry in entries {
        let entry = entry.with_context(|| format!("reading {}", at.display()))?;
        let rel_path = rel.join(entry.file_name());
        let meta = fs::symlink_metadata(entry.path())
            .with_context(|| format!("reading {}", entry.path().display()))?;
        if !keep.contains(&rel_path) {
            match meta.is_dir() {
                true => fs::remove_dir_all(entry.path()),
                false => fs::remove_file(entry.path()),
            }
            .with_context(|| format!("removing {}", entry.path().display()))?;
        } else if meta.is_dir() {
            prune(dst, &rel_path, keep)?;
        }
    }
    Ok(())
}

