    #[test]
    fn every_volume_of_this_repos_kits_goes_to_ram_and_nothing_else_changes() {
        let kits_dir = Catalog::load().unwrap().kits_dir;
        let mut with_volumes = Vec::new();
        for entry in fs::read_dir(&kits_dir).unwrap() {
            let dir = entry.unwrap().path();
            let Ok(text) = fs::read_to_string(kits::descriptor_path(&dir)) else {
                continue;
            };
            let original = kits::load_descriptor(&text).unwrap();
            let kit = dir.file_name().unwrap().to_string_lossy().to_string();
            if disk_volumes(&original) == 0 {
                assert!(descriptor_in_ram(&text, &kit).is_err(), "{kit}");
                continue;
            }
            let copy = descriptor_in_ram(&text, &kit).unwrap();
            assert!(copy.starts_with("# syntax=docker/sandbox-kit:3\n"), "{kit}");
            let back = kits::load_descriptor(&copy).unwrap();
            assert_eq!(disk_volumes(&back), 0, "{kit}");
            let (was, now) = (kits::capabilities(&original), kits::capabilities(&back));
            assert_eq!(was.len(), now.len(), "{kit}");
            for (a, b) in was.iter().zip(&now) {
                assert_eq!((&a.kind, a.optional), (&b.kind, b.optional), "{kit}");
                match a.kind == VOLUME {
                    true => {
                        assert_eq!(b.config["tmpfs"].as_bool(), Some(true), "{kit}");
                        assert_eq!(a.config["path"], b.config["path"], "{kit}");
                        assert_eq!(a.config["size"], b.config["size"], "{kit}");
                    }
                    false => assert_eq!(a.config, b.config, "{kit}"),
                }
            }
            for key in [
                "schemaVersion",
                "kind",
                "displayName",
                "description",
                "build",
            ] {
                assert_eq!(original[key], back[key], "{kit} {key}");
            }
            with_volumes.push(kit);
        }
        with_volumes.sort();
        assert_eq!(
            with_volumes,
            [
                "claude-anthropic",
                "claude-bare-local",
                "claude-litellm",
                "claude-local",
                "claude-token",
                "host-npm",
                "host-pip"
            ]
        );
    }

