    /// A kit folder of `kit` in a scratch place of its own, with the descriptor `descriptor`, a
    /// Dockerfile and a `files/` tree.
    fn fixture(tag: &str, kit: &str, descriptor: &str) -> PathBuf {
        let dir = std::env::temp_dir()
            .join(format!("aisbx-tmpfs-fixture-{tag}-{}", std::process::id()))
            .join(kit);
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(dir.join("files").join("probe")).unwrap();
        fs::write(kits::descriptor_path(&dir), descriptor).unwrap();
        fs::write(
            dir.join(format!("{kit}.dockerfile")),
            "FROM scratch\nCOPY files/ /x/\n",
        )
        .unwrap();
        fs::write(
            dir.join("files").join("probe").join("hook.sh"),
            "#!/bin/sh\nexit 0\n",
        )
        .unwrap();
        dir
    }

    fn probe(kit: &str, volumes: &str) -> String {
        format!(
            "# syntax=docker/sandbox-kit:3\n# A probe.\nschemaVersion: \"3\"\nkind: mixin\n\
             displayName: {kit}\ndescription: >-\n  Two lines\n  folded.\n\ncapabilities:\n\
             {volumes}\
             \x20 - type: com.docker.sandbox/lifecycle@1\n    config:\n      startup:\n\
             \x20       - command: [\"sh\", \"/x/probe/hook.sh\"]\n          user: \"0\"\n"
        )
    }

    /// Every file of the folder below `root`, with its bytes, by its path below `root`.
    fn tree(root: &Path) -> Vec<(PathBuf, Vec<u8>)> {
        let mut out = Vec::new();
        let mut stack = vec![root.to_path_buf()];
        while let Some(dir) = stack.pop() {
            for entry in fs::read_dir(&dir).unwrap() {
                let path = entry.unwrap().path();
                if path.is_dir() {
                    stack.push(path);
                } else {
                    let bytes = fs::read(&path).unwrap();
                    out.push((path.strip_prefix(root).unwrap().to_path_buf(), bytes));
                }
            }
        }
        out.sort();
        out
    }

