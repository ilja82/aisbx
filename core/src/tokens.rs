//! Named Anthropic setup tokens: a generated env-only v3 mixin per token name makes a sandbox send
//! the token's placeholder ([`crate::sbx::named_token_placeholder`]). It is a kit, because a
//! sandbox-scoped secret with that placeholder shadows the global one and breaks the swap.

use std::fs;
use std::path::PathBuf;

use anyhow::{Context, Result};

use crate::sbx;
use crate::state::state_dir;

/// Marks a kit directory as the wiring for a named token, whose name follows it.
pub const KIT_PREFIX: &str = "token-";

/// Where the generated kits live. Under the test guard, a scratch folder instead.
pub fn kits_dir() -> PathBuf {
    if cfg!(any(test, feature = "test-support")) {
        std::env::temp_dir().join("aisbx-tests-tokens")
    } else {
        state_dir().join("tokens")
    }
}

pub fn kit_dir(token: &str) -> PathBuf {
    kits_dir().join(format!("{KIT_PREFIX}{token}"))
}

/// The token a kit directory name is the wiring for, or `None` for any other kit.
pub fn name_of_kit(dir_name: &str) -> Option<&str> {
    dir_name
        .strip_prefix(KIT_PREFIX)
        .filter(|name| !name.is_empty())
}

/// Write the kit for a token, and return the directory to pass to `sbx create --kit`. Rewritten
/// every time: a half-written or hand-edited kit would point a container at the wrong account.
pub fn ensure_kit(token: &str) -> Result<PathBuf> {
    let dir = kit_dir(token);
    fs::create_dir_all(&dir)
        .with_context(|| format!("creating the kit directory for token “{token}”"))?;
    fs::write(crate::kits::descriptor_path(&dir), descriptor(token))
        .with_context(|| format!("writing the kit for token “{token}”"))?;
    Ok(dir)
}

/// Drop the generated kit for a token, once the token itself is gone from the host. A missing
/// directory is not an error.
pub fn remove_kit(token: &str) -> Result<()> {
    let dir = kit_dir(token);
    match fs::remove_dir_all(&dir) {
        Ok(()) => Ok(()),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(e) => Err(e).with_context(|| format!("removing {}", dir.display())),
    }
}

/// The kit's descriptor: a v3 mixin whose whole content is one variable, image ENV in an inline
/// `build:`. The name is a checked token name and the placeholder is built from it, so neither
/// holds a quote.
fn descriptor(token: &str) -> String {
    let placeholder = sbx::named_token_placeholder(token);
    let (host, env) = (sbx::TOKEN_HOST, sbx::TOKEN_ENV);
    format!(
        "# syntax=docker/sandbox-kit:3\n\
         # Generated by aisbx — do not edit; rewritten whenever a sandbox is built on this token.\n\
         #\n\
         # Points a sandbox at the Anthropic setup token stored on this host under the name\n\
         # \"{token}\". The variable below is only a placeholder: the real token stays in the host\n\
         # keychain and the sbx proxy swaps it in on requests to {host}. Any number of sandboxes\n\
         # can carry this kit — they all authenticate as that one account, and re-storing the token\n\
         # under the same placeholder rotates it for all of them at once, with nothing rebuilt.\n\
         #\n\
         #   sbx secret set-custom --host {host} --placeholder {placeholder}\n\
         schemaVersion: \"3\"\n\
         kind: mixin\n\
         displayName: \"Setup token: {token}\"\n\
         description: \"Anthropic setup token stored on this host as {token}.\"\n\
         \n\
         build: |\n\
         \x20 FROM scratch\n\
         \x20 ENV {env}=\"{placeholder}\"\n"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_test_build_writes_token_kits_to_a_scratch_folder() {
        assert!(kits_dir().starts_with(std::env::temp_dir()));
        assert!(kit_dir("personal").starts_with(kits_dir()));
    }

    #[test]
    fn a_kit_name_carries_the_token_it_wires() {
        assert_eq!(name_of_kit("token-private"), Some("private"));
        assert_eq!(name_of_kit("token-"), None);
        assert_eq!(name_of_kit("claude-token"), None);
        assert_eq!(name_of_kit("jdk25"), None);
        let dir = kit_dir("work");
        assert_eq!(
            dir.file_name()
                .and_then(|n| n.to_str())
                .and_then(name_of_kit),
            Some("work")
        );
    }

    #[test]
    fn the_generated_descriptor_sets_the_placeholder_and_nothing_else() {
        let text = descriptor("private");
        assert!(
            text.starts_with("# syntax=docker/sandbox-kit:3\n"),
            "{text}"
        );
        let doc = crate::kits::load_descriptor(&text).unwrap();
        assert_eq!(doc["schemaVersion"].as_str(), Some("3"));
        assert_eq!(doc["kind"].as_str(), Some("mixin"));
        assert_eq!(
            doc["build"].as_str(),
            Some("FROM scratch\nENV CLAUDE_CODE_OAUTH_TOKEN=\"sbx-cs-aisbx-tok-private\"\n")
        );
        assert!(doc["capabilities"].is_badvalue(), "{text}");
    }

    #[test]
    fn the_generated_kit_reads_back_as_a_mixin() {
        let dir = ensure_kit("aisbx-selftest").expect("writing a kit into the state dir");
        let kit = crate::kits::Kit::read(&dir).expect("the generated kit parses");
        assert_eq!(kit.name, "token-aisbx-selftest");
        assert!(kit.credentials.is_empty(), "{kit:?}");
        assert_eq!(kit.kit_add_blocker, None);
        assert!(!kit.is_workload);
        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn removing_a_kit_is_idempotent() {
        let dir = ensure_kit("aisbx-selftest-rm").expect("writing a kit into the state dir");
        assert!(dir.is_dir());
        remove_kit("aisbx-selftest-rm").expect("removing it");
        assert!(!dir.exists());
        remove_kit("aisbx-selftest-rm").expect("removing it again");
    }

    #[test]
    #[ignore = "runs sbx; part of the live suite"]
    fn live_sbx_validates_the_generated_kit() {
        let dir = ensure_kit("aisbx-selftest").expect("writing a kit into the state dir");
        let out = std::process::Command::new("sbx")
            .args(["kit", "validate", "--json"])
            .arg(&dir)
            .output()
            .expect("running `sbx kit validate`");
        let text = format!(
            "{}{}",
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        );
        println!("sbx kit validate {} →\n{text}", dir.display());
        std::fs::remove_dir_all(&dir).ok();
        assert!(out.status.success(), "{text}");
        let report: serde_json::Value = serde_json::from_slice(&out.stdout).expect("JSON");
        assert_eq!(report["valid"], serde_json::json!(true), "{text}");
        assert_eq!(report["warnings"], serde_json::json!([]), "{text}");
        assert!(!text.to_lowercase().contains("deprecat"), "{text}");
    }
}
